"""
Run the full analysis and write reports/strategy_report.md.

    python -m src.run
"""
from pathlib import Path

import pandas as pd

from src import charts, forecast as fc, market as mk, potential, swot
from src.data import load_all

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
CHARTS = OUT / "charts"
REPORTS = ROOT / "reports"


def md_table(df: pd.DataFrame, index=True) -> str:
    """Small markdown table writer (avoids needing the 'tabulate' package)."""
    df = df.reset_index() if index else df
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append("-" if v != v else f"{v:,.1f}")       # v != v is True only for NaN
            elif isinstance(v, int) and v > 9999:
                cells.append(f"{v:,}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    OUT.mkdir(exist_ok=True)
    CHARTS.mkdir(exist_ok=True)
    REPORTS.mkdir(exist_ok=True)

    market, models, reviews = load_all()
    year = int(market["year"].max())
    first = int(market["year"].min())

    # --- descriptive analysis
    units, shares = mk.yearly_fuel_mix(market)
    growth = mk.growth_by_fuel(units, first + 1, year)          # skip first year (EV base too small)
    overview = mk.company_overview(market)
    seg = mk.ev_segment_shares(market)
    perf = mk.model_performance(models, year)
    mix = mk.ev_model_mix(models)
    scores = mk.review_summary(reviews)

    # --- forecast + potential
    ev_monthly = fc.monthly_ev_share(market)
    bt = fc.backtest(ev_monthly)
    forecast = fc.scenario_forecast(market)
    pot = potential.potential_table(forecast, overview, models)

    # --- SWOT
    fuel_by_model = models.drop_duplicates("model").set_index("model")["fuel_type"].to_dict()
    ctx = {"overview": overview, "ev_segment": seg, "ev_model_mix": mix, "model_perf": perf,
           "growth": growth, "potential": pot, "forecast": forecast,
           "weak": swot.weak_aspects(reviews, fuel_by_model)}
    s = swot.build_swot(ctx)
    recs = swot.recommendations(ctx)

    # --- save tables
    for name, df in {"fuel_mix_share": shares, "fuel_growth": growth, "company_overview": overview,
                     "ev_segment_share": seg, "model_performance": perf, "ev_model_mix": mix,
                     "forecast_backtest": bt, "forecast_scenarios": forecast, "ev_potential_2030": pot}.items():
        df.to_csv(OUT / f"{name}.csv")

    # --- charts
    charts.ev_share_forecast(ev_monthly, forecast, CHARTS)
    charts.ev_vs_petrol_units(units, forecast, CHARTS)
    charts.ev_segment_share(seg, CHARTS)
    charts.ev_model_mix(mix, CHARTS)
    charts.review_heatmap(scores, CHARTS)

    # --- report
    base30 = forecast[(forecast["scenario"] == "base") & (forecast["year"] == 2030)].iloc[0]
    r = [
        "# Strategic Analysis of the Automotive Market: Company X",
        "",
        "> Simulated case-study data (see `data/README.md`). Generated by `python -m src.run`.",
        "",
        "## 1. Summary",
        f"- Company X holds **{overview.loc[year, 'company_share_of_ev_segment_pct']:.1f}%** of the country's EV "
        f"segment ({year}), down from {overview['company_share_of_ev_segment_pct'].max():.1f}% at its peak.",
        f"- EVs are only **{shares.loc[year, 'EV']:.1f}%** of new car sales but grew "
        f"**{growth.loc['EV', 'cagr_pct']:.0f}% a year** ({first + 1}-{year}); petrol grew "
        f"{growth.loc['Petrol', 'cagr_pct']:.0f}%.",
        f"- Base scenario: EVs reach **{base30['ev_share_pct']:.0f}%** of sales in 2030 "
        f"({base30['ev_units']:,} units), petrol falls to {base30['petrol_share_pct']:.0f}%.",
        "- Main recommendation: improve the volume EV (X-City EV) on range and charging to defend share.",
        "",
        "## 2. Market today",
        "Share of new car sales by fuel type (%):",
        "",
        md_table(shares),
        "",
        "Growth by fuel type:",
        "",
        md_table(growth),
        "",
        "![EV segment](../outputs/charts/ev_segment_share.png)",
        "",
        "## 3. Company X",
        md_table(overview[["company_market_share_pct", "company_share_of_ev_segment_pct",
                           "ev_pct_of_company_sales"]]),
        "",
        f"Models in {year}:",
        "",
        md_table(perf),
        "",
        "![EV model mix](../outputs/charts/ev_model_mix.png)",
        "![Review scores](../outputs/charts/review_scores.png)",
        "",
        "## 4. Future trends: EV vs petrol",
        "EV share is modelled as an S-curve (logistic). The market is still near the bottom of the curve, so "
        "the saturation level can't be estimated from the data. It is fixed per scenario "
        "(slow 30%, base 50%, fast 70%) and the speed/midpoint are fitted.",
        "",
        f"Backtest (fit to {first}-2022, test on 2023-{year}, monthly EV share):",
        "",
        md_table(bt, index=False),
        "",
        "The logistic scenarios all score about the same, so the data supports the S-curve shape "
        "but cannot choose between saturation levels. That is why the forecast is given as scenarios.",
        "",
        md_table(forecast[forecast["year"].isin([2025, 2027, 2030])]
                 [["scenario", "year", "ev_share_pct", "ev_units", "petrol_share_pct", "petrol_units"]], index=False),
        "",
        "![EV share forecast](../outputs/charts/ev_share_forecast.png)",
        "![EV vs petrol](../outputs/charts/ev_vs_petrol_units.png)",
        "",
        "## 5. EV market potential for Company X (2030)",
        f"Revenue uses Company X's {year} average EV price (US$ {pot.attrs['price']:,.0f}), held constant.",
        "",
        md_table(pot, index=False),
        "",
        "## 6. SWOT",
    ]
    for quadrant, points in s.items():
        r += ["", f"**{quadrant}**", ""] + [f"- {p}" for p in points]
    r += ["", "## 7. Recommendations", ""] + [f"{i}. {x}" for i, x in enumerate(recs, 1)]
    r += ["", "## 8. Limitations",
          "- Simulated data; methods are the point, not the exact numbers.",
          "- Forecasts are trend-based and ignore policy changes (subsidies, fuel prices), which can move EV adoption a lot.",
          "- Customer scores are averages; no competitor review data, so model weaknesses are judged in absolute terms.",
          "- Revenue assumes constant prices and model mix."]
    (REPORTS / "strategy_report.md").write_text("\n".join(r) + "\n")
    print((REPORTS / "strategy_report.md").read_text())


if __name__ == "__main__":
    main()
